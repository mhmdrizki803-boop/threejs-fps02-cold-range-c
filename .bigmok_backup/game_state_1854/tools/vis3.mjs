import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--use-gl=swiftshader','--enable-unsafe-swiftshader','--no-sandbox'] });
const p = await b.newPage({ viewport:{width:800,height:500} });
await p.goto('http://127.0.0.1:8777/game/index.html');
await p.waitForFunction(()=>window.__fps);
await p.click('#play'); await p.waitForTimeout(200);
const out = await p.evaluate(async ()=>{
  const g=window.__fps.game;
  for (const e of [...g.enemies]) e.dispose(g.scene); g.enemies.length=0;
  const mod = await import('/game/src/enemy.js');
  g.player.position.set(0,0,16); g.player.yaw=0; g.player.pitch=0;
  g.player.syncCamera(0);
  // Put the target at 5m so it fills a readable slice of the frame.
  const e = new mod.Enemy(g.rng, {x:0,z:11}, 1);
  e.mesh.rotation.y = Math.PI;
  e.state='engage'; e.lastSeen.set(0,0,16);
  g.scene.add(e.mesh); g.enemies.push(e);
  g.scene.updateMatrixWorld(true); g.camera.updateMatrixWorld(true);
  const v = e.hitHead.getWorldPosition(e.position.clone()); v.project(g.camera);
  const head=[Math.round((v.x*.5+.5)*800), Math.round((-v.y*.5+.5)*500)];
  const v2 = e.hitTorso.getWorldPosition(e.position.clone()); v2.project(g.camera);
  const torso=[Math.round((v2.x*.5+.5)*800), Math.round((-v2.y*.5+.5)*500)];
  const v3 = e.hitLegs.getWorldPosition(e.position.clone()); v3.project(g.camera);
  const legs=[Math.round((v3.x*.5+.5)*800), Math.round((-v3.y*.5+.5)*500)];
  g.renderer.render(g.scene,g.camera);
  return { head, torso, legs };
});
console.log(JSON.stringify(out));
await p.waitForTimeout(200);
await p.screenshot({path:'shot-close.png'});
await b.close();
